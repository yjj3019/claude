def files_in(root: Path) -> list[Path]:
    _safe_tree(root)
    return sorted((path.relative_to(root) for path in root.rglob("*")
                   if path.is_file() and "__pycache__" not in path.parts
                   and path.suffix not in {".pyc", ".pyo"}), key=lambda p: p.as_posix())


def payload_files(root: Path) -> dict[str, bytes]:
    _safe_path(root)
    selected = {Path(name) for name in FILES}
    selected.update(Path("docs") / name for name in RUNTIME_DOCS)
    for name in TREES:
        folder = root / name
        if not folder.is_dir():
            raise ValueError(f"Missing runtime directory: {name}")
        for rel in files_in(folder):
            if rel.suffix not in SUFFIXES:
                continue
            if name == "skills" and rel.parts[:2] == ("ai-delegation-loop", "tests") \
                    and rel.name != "acceptance-cases.md":
                continue
            selected.add(Path(name) / rel)
    result = {}
    for rel in sorted(selected):
        path = root / rel
        _safe_path(path)
        if not path.is_file():
            raise ValueError(f"Missing regular runtime file: {rel}")
        result[rel.as_posix()] = path.read_bytes()
    result["README.md"] = README.encode("utf-8")
    validate_links(result)
    return result


def validate_links(files: dict[str, bytes]) -> None:
    # Report missing references; never follow links to add arbitrary source files.
    for name, content in files.items():
        if not name.endswith(".md"):
            continue
        fence = ""
        for line in content.decode("utf-8-sig").splitlines():
            marker = re.match(r"^\s*(`{3,}|~{3,})", line)
            if marker:
                token = marker.group(1)
                if not fence:
                    fence = token
                elif token[0] == fence[0] and len(token) >= len(fence):
                    fence = ""
                continue
            if fence:
                continue
            for target in MARKDOWN_LINK_RE.findall(line):
                url = urlsplit(target.strip("<>"))
                if url.scheme or url.netloc or not url.path:
                    continue
                rel = posixpath.normpath(posixpath.join(posixpath.dirname(name), unquote(url.path)))
                if rel.startswith(("../", "/")) or not (
                    rel in files or any(item.startswith(rel.rstrip("/") + "/") for item in files)
                ):
                    raise ValueError(f"Missing or external payload link: {name} -> {target}")


def build(root: Path = ROOT, *, check: bool = False) -> bool:
    expected = payload_files(root)
    dest = root / DESTINATION
    _safe_path(dest)
    actual = {rel.as_posix(): (dest / rel).read_bytes() for rel in files_in(dest)} if dest.exists() else {}
    missing = sorted(expected.keys() - actual.keys())
    extra = sorted(actual.keys() - expected.keys())
    changed = sorted(name for name in expected.keys() & actual.keys() if expected[name] != actual[name])
    if check:
        if missing or extra or changed:
            for label, names in (("missing", missing), ("extra", extra), ("changed", changed)):
                if names:
                    print(f"Plugin payload {label}: {', '.join(names)}")
            return False
        print(f"Plugin payload is in sync ({len(expected)} files).")
        return True
    if extra:
        raise ValueError("Unexpected payload files; review manually before rebuilding: " + ", ".join(extra))
    # Preflight every target before writing. Individual writes are atomic; a
    # partial build fails --check and must not be released.
    for name in expected:
        target = dest / name
        _safe_path(target)
        if target.exists() and not target.is_file():
            raise ValueError(f"Expected a payload file: {target}")
    for name in missing + changed:
        target = dest / name
        target.parent.mkdir(parents=True, exist_ok=True)
        temporary = None
        try:
            with tempfile.NamedTemporaryFile(dir=target.parent, delete=False) as stream:
                temporary = Path(stream.name)
                stream.write(expected[name])
            os.replace(temporary, target)
        finally:
            if temporary is not None and temporary.exists():
                temporary.unlink()
    print(f"Generated plugin payload ({len(expected)} files; {len(missing) + len(changed)} updated).")
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Report missing, extra or changed files without writing")
    args = parser.parse_args()
    try:
        return 0 if build(check=args.check) else 1
    except (OSError, ValueError) as error:
        print(f"Plugin build failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
